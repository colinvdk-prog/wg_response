"""Render the calibration matrix on the REPAIRED corpora in the exact format
of scratch_review/calmatrix_report.py (docs/calibration/calibration_matrix_
2026-09-03.md / -09-11.md), as a new document:
docs/calibration/calibration_matrix_2026-09-27_corrected.md.

Inputs: scratch_review/hindcast_stacked/results/after/<corpus>__<label>.json
(run_all.py). The dated matrices of record are not edited.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "scratch_review"))
from tools import hindcast_lib as H  # noqa: E402
import calmatrix_report as CR  # noqa: E402

DEST = os.path.join(ROOT, "docs", "calibration",
                    "calibration_matrix_2026-09-27_corrected.md")


def main() -> int:
    out = ["# Hindcast calibration matrix — 2026-09-27 (corrected corpora)",
           "",
           "The 2026-09-03 and 2026-09-11 matrices re-run, variant for variant, on",
           "the REPAIRED August and July-OOS corpora: every WFIGS snapshot is now its",
           "first-published polygon instead of a stack of same-time versions that the",
           "even-odd rasterizer cancelled (tools/hindcast_lib.py SNAPSHOT RULE; record,",
           "method and before/after in docs/calibration/stacked_rings_fix_2026-09-27.md).",
           "Same engine, same capture times, same pairing law and scorecard",
           "(docs/calibration/SCORECARD.md) as the dated matrices; every variant carries",
           "the as-deployed gust blend 0.5. Generated by",
           "scratch_review/hindcast_stacked/corrected_matrix.py from",
           "scratch_review/hindcast_stacked/results/after/. Dangerous polarity: late",
           "miss UP, PIT extreme mass UP. Area/skill show what coverage costs.",
           ""]
    for corpus, name in (("aug", "August 2026 corpus (scratch_review/hindcast_aug_data), repaired"),
                         ("oos", "July 2026 OOS corpus (scratch_review/hindcast_oos_data), repaired")):
        out += [f"## {name}", "", CR.HEADER]
        for label in CR.ORDER:
            path = os.path.join(HERE, "results", "after", f"{corpus}__{label}.json")
            with open(path, "r", encoding="utf-8") as f:
                d = json.load(f)
            if d.get("label") != label:
                raise SystemExit(f"INTEGRITY: {path} stores label {d.get('label')!r}")
            pairs = [H.PairMetrics(**{k: v for k, v in p.items() if k in CR.FIELDS})
                     for p in d["pairs"]]
            out.append(CR.row(f"{label} — {CR.DESC.get(label, '')}", H.pool_metrics(pairs)))
        out.append("")
    with open(DEST, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {DEST}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
